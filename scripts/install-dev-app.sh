#!/usr/bin/env bash
# macOS: install "Symphony Dev.app" into /Applications. Opening it rebuilds
# the latest code from this repo and launches it, so it always runs what's
# on disk. A loading window shows build progress the whole time. It works from Spotlight, Raycast, Launchpad and the Dock.
# Re-run this script if the repo or the Rust toolchain moves.
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
APP="${1:-/Applications}/Symphony Dev.app"
# One Symphony Dev per Mac, built from the main checkout. A copy from another
# worktree (in any folder, since Spotlight and Raycast index them all) shows
# up under the same name and runs someone's unfinished branch. Test
# branches with `cargo run -p symphony-app` instead.
if [ "$(git -C "$REPO" rev-parse --git-dir)" != "$(git -C "$REPO" rev-parse --git-common-dir)" ]; then
  echo "This is a secondary worktree. Install Symphony Dev from the main checkout;" >&2
  echo "to test this branch, use: cargo run -p symphony-app" >&2
  exit 1
fi
RUSTUP_HOME="${RUSTUP_HOME:-$HOME/.rustup}"
CARGO_HOME="${CARGO_HOME:-$HOME/.cargo}"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$REPO/crates/symphony-app/assets/Symphony.icns" "$APP/Contents/Resources/"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Symphony Dev</string>
  <key>CFBundleDisplayName</key><string>Symphony Dev</string>
  <key>CFBundleIdentifier</key><string>io.github.tdemers218.symphony.dev</string>
  <key>CFBundleExecutable</key><string>symphony-dev</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleIconFile</key><string>Symphony.icns</string>
  <key>CFBundleShortVersionString</key><string>dev</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict></plist>
PLIST

cat > "$APP/Contents/MacOS/symphony-dev" <<SCRIPT
#!/bin/bash
# Generated by scripts/install-dev-app.sh
export RUSTUP_HOME="$RUSTUP_HOME"
export CARGO_HOME="$CARGO_HOME"
export PATH="/opt/homebrew/opt/rustup/bin:\$CARGO_HOME/bin:/usr/bin:/bin:/usr/sbin:/sbin"
REPO="$REPO"
LOG="\$HOME/Library/Logs/Symphony Dev.log"
alert() { osascript -e "display alert \"\$1\" message \"\$2\"" >/dev/null 2>&1; }
if [ ! -d "\$REPO" ]; then
  alert "Symphony Dev can't find the project" "Expected it at \$REPO. Is that drive connected?"
  exit 1
fi
cd "\$REPO"
# Preferred: the launcher's developer mode shows a loading screen while it
# builds (DESIGN §17), then starts Symphony.
if [ -x "\$REPO/target/release/symphony-launcher" ]; then
  exec nice -n 5 "\$REPO/target/release/symphony-launcher" --dev "\$REPO"
fi
if ! nice -n 10 cargo build --release -p symphony-app >"\$LOG" 2>&1; then
  alert "Symphony didn't build" "The latest code has an error. Details are in ~/Library/Logs/Symphony Dev.log."
  exit 1
fi
exec "\$REPO/target/release/symphony"
SCRIPT
chmod +x "$APP/Contents/MacOS/symphony-dev"
echo "Building the launcher once, so Symphony Dev can show build progress..."
( cd "$REPO" && RUSTUP_HOME="$RUSTUP_HOME" CARGO_HOME="$CARGO_HOME" PATH="/opt/homebrew/opt/rustup/bin:$CARGO_HOME/bin:$PATH" cargo build --release -p symphony-launcher )
echo "Installed $APP"
